/**
 * Helper to normalize order IDs (e.g., "#1002", "ORD-1002", "1002" -> "1002")
 */
export function normalizeOrderId(rawId: string): string {
  return rawId.trim().replace(/^(order\s*#?|ord-?|#)/i, '').trim();
}
